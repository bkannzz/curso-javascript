let idade = 19

if (idade < 12) {
    console.log(`Com ${idade} anos de idade, você é um criança!`)
} else if (idade < 18) {
    console.log(`Com ${idade} anos de idade, você é um adolescente!`)
} else if (idade < 65) {
    console.log(`Com ${idade} anos de idade, você é um adulto!`)
} else {
    console.log(`Com ${idade} anos de idade, você é um idoso!`)
}